##Cómo afecta esto a tus clases
##Clase	Responsabilidad principal
##Jugador	Vida, energía, elección de cartas y participación en la pelea.
##Persona / Maquina	Representar los participantes humanos y la máquina.
##Personaje	Estadísticas, habilidades y acciones particulares.
##Pila	Guardar las cartas elegidas en el orden de ejecución; permitir agregar y deshacer.
##Carta	Nombre, costo de energía, disponibilidad, ataque, defensa y acción asociada.
##Accion	Ejecutar comportamientos como atacar, defender o realizar una acción especial.
##Pelea	Controlar turnos, procesar resultados y determinar cuándo termina el combate.